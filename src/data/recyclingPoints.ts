export const cleanLocationStr = (str: string): string => {
  return (str || '')
    .toLowerCase()
    .replace(/['‘ʻ’`]/g, '')
    .replace(/viloyati|shahri|tumani|respublikasi/g, '')
    .replace(/\s+/g, ' ')
    .trim();
};

export const getAccurateDropoffPoints = (
  points: RecyclingPoint[],
  regionName: string,
  districtName?: string
): RecyclingPoint[] => {
  const normReg = cleanLocationStr(regionName);
  const normDist = districtName && districtName !== 'all' ? cleanLocationStr(districtName) : '';

  if (normDist) {
    // 1. Direct district match
    const directMatches = points.filter(p => {
      const pReg = cleanLocationStr(p.region);
      const pDist = cleanLocationStr(p.district);
      const regMatch = pReg.includes(normReg) || normReg.includes(pReg);
      const distMatch = pDist.includes(normDist) || normDist.includes(pDist);
      return regMatch && distMatch;
    });

    if (directMatches.length > 0) {
      return directMatches;
    }
  }

  // 2. Region matches
  return points.filter(p => {
    const pReg = cleanLocationStr(p.region);
    return pReg.includes(normReg) || normReg.includes(pReg);
  });
};

